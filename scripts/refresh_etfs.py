# The eleven Select Sector SPDRs ARE the GICS sectors, as funds.
SECTOR_ETF = {
    "Information Technology": "XLK",
    "Financials": "XLF",
    "Health Care": "XLV",
    "Consumer Discretionary": "XLY",
    "Consumer Staples": "XLP",
    "Energy": "XLE",
    "Industrials": "XLI",
    "Materials": "XLB",
    "Real Estate": "XLRE",
    "Utilities": "XLU",
    "Communication Services": "XLC",
}


def probe(t):
    url = (f"https://query1.finance.yahoo.com/v8/finance/chart/{t}"
           "?interval=1d&range=5y")
    r = requests.get(url, headers=HEADERS, timeout=25)
    if r.status_code != 200:
        return None, f"HTTP {r.status_code}"
    d = r.json()["chart"]["result"][0]
    closes = [c for c in d["indicators"]["quote"][0]["close"] if c is not None]
    meta = d["meta"]
    name = meta.get("shortName") or meta.get("longName") or t
    if meta.get("currency") != "USD":
        return None, f"currency {meta.get('currency')}"
    return (name.strip(), len(closes)), None


def main():
    flat = [t for g in ETF_GROUPS.values() for t in g]
    dupes = {t for t in flat if flat.count(t) > 1}
    if dupes:
        print(f"ABORTING - ticker in more than one group: {sorted(dupes)}",
              file=sys.stderr)
        sys.exit(1)
    missing = sorted(set(SECTOR_ETF.values()) - set(ETF_GROUPS["Sector SPDR"]))
    if missing:
        print(f"ABORTING - SECTOR_ETF names not in the Sector SPDR group: {missing}",
              file=sys.stderr)
        sys.exit(1)

    names, bars, fail = {}, {}, {}
    for t in flat:
        got, err = probe(t)
        if err:
            fail[t] = err
        else:
            names[t], bars[t] = got
    if fail:
        print("ABORTING - every curated ETF must resolve on Yahoo:", file=sys.stderr)
        for t, e in sorted(fail.items()):
            print(f"  - {t}: {e}", file=sys.stderr)
        sys.exit(1)

    with open(OUT, "w") as f:
        f.write('"""GENERATED by scripts/refresh_etfs.py - do not hand-edit.\n\n'
                "Groups are curated in that script; labels come from Yahoo.\n"
                '"""\n\n')
        f.write("ETF_GROUPS = {\n")
        for g, ts in ETF_GROUPS.items():
            f.write(f'    "{g}": {ts!r},\n')
        f.write("}\n\nSECTOR_ETF = {\n")
        for k, v in SECTOR_ETF.items():
            f.write(f'    "{k}": "{v}",\n')
        f.write("}\n\nETF_NAME = {\n")
        for t in flat:
            f.write(f'    "{t}": "{names[t]}",\n')
        f.write("}\n")

    print(f"wrote {OUT}")
    for g, ts in ETF_GROUPS.items():
        print(f"   {len(ts):>3}  {g}")
    print(f"   {len(flat):>3}  TOTAL")
    thin = {t: n for t, n in bars.items() if n < 1000}
    print("\nunder 5y of history (will be excluded from the 5y views, by the "
          "existing minimum-history rule, not special-cased):")
    for t, n in sorted(thin.items(), key=lambda kv: kv[1]):
        print(f"   {t:<6} {n:>5} bars   {names[t]}")


if __name__ == "__main__":
    main()
