"""Regenerate us_market_core/etf_universe.py - the ETF side of the board.

The groups are hand-curated and deliberate; only the LABELS are fetched, so a
Yahoo hiccup can change a display name but can never change what the board
covers.

WHY THE GROUPS EXIST AT ALL - and a correction worth recording. They are NOT
a normalisation device. rrg_tail z-scores each symbol over ITS OWN history, so
what a bubble shows does not depend on what else is plotted beside it; putting
SHV (a 3-month T-bill fund that barely moves) on the same chart as SOXX
distorts neither of them. The groups exist for two plainer reasons: 112 ETFs
and 503 stocks on one canvas is unreadable, and a group is the unit you
actually think in when reading rotation - bonds against equities, defensives
against cyclicals. Switching group is switching question, not switching scale.

Sector SPDRs are special-cased: they are the eleven GICS sectors as tradeable
funds, so they double as the sector view's series. That is better than an
equal-weight basket of constituents (what the Indian board must build, lacking
a liquid sectoral index per group) because it is the thing you can actually
buy, with real weights.
"""

